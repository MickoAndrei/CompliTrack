import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { icons } from 'lucide';

export function usedIcons() {
    const found = new Set();
    function scan(directory) {
        for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
            const filename = path.join(directory, entry.name);
            if (entry.isDirectory()) scan(filename);
            else if (/\.(php|js)$/.test(filename) && filename !== path.join('resources', 'js', 'icons.js')) {
                const source = fs.readFileSync(filename, 'utf8');
                // Includes literal data-lucide values and icon names stored in PHP/JS arrays.
                for (const [, value] of source.matchAll(/['"]([a-z][a-z0-9-]*)['"]/g)) {
                    const name = value.replace(/(^|-)([a-z0-9])/g, (_, _separator, letter) => letter.toUpperCase());
                    if (icons[name]) found.add(name);
                }
            }
        }
    }
    scan('resources');
    scan('app');
    return [...found].sort();
}

export function registrySource() {
    const names = usedIcons();
    return `// Generated by node scripts/generate-icon-registry.mjs. Keep explicit imports for tree shaking.\nimport {\n    ${names.join(',\n    ')},\n} from 'lucide';\n\nexport const icons = {\n    ${names.join(',\n    ')},\n};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    fs.writeFileSync('resources/js/icons.js', registrySource());
    console.log(`Registered ${usedIcons().length} icons used by application source.`);
}
